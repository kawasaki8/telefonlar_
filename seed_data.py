def seed_database():
    init_db()
    conn = get_connection()
    cursor = conn.cursor()

    print(f"Boshlang'ich smartfonlar kiritilmoqda ({len(SMARTPHONES_DATA)} ta model)...")

    for item in SMARTPHONES_DATA:
        # 1. Smartphones main table
        cursor.execute("""
        INSERT OR REPLACE INTO smartphones (id, name, brand, series, category, release_year, release_date, image_url, colors_json, is_featured, views)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            item["id"],
            item["name"],
            item["brand"],
            item["series"],
            item["category"],
            item["release_year"],
            item["release_date"],
            item["image_url"],
            item["colors_json"],
            item["is_featured"],
            0
        ))

        # 2. Specifications
        s = item["specs"]
        cursor.execute("""
        INSERT OR REPLACE INTO specifications (
            phone_id, display_size, display_tech, resolution, refresh_rate,
            chipset, chipset_manufacturer, cpu_arch, cpu_cores, max_clock, process_node,
            gpu, processor_explanation, main_camera, front_camera, camera_features,
            battery_mah, charging_speed, os, ram, storage, dimensions, weight, water_resistance
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            item["id"],
            s["display_size"],
            s["display_tech"],
            s["resolution"],
            s["refresh_rate"],
            s["chipset"],
            s["chipset_manufacturer"],
            s["cpu_arch"],
            s["cpu_cores"],
            s["max_clock"],
            s["process_node"],
            s["gpu"],
            s["processor_explanation"],
            s["main_camera"],
            s["front_camera"],
            s.get("camera_features", ""),
            s["battery_mah"],
            s["charging_speed"],
            s["os"],
            s["ram"],
            s["storage"],
            s["dimensions"],
            s["weight"],
            s["water_resistance"]
        ))

        # 3. AnTuTu Benchmark
        b = item["antutu"]
        cursor.execute("""
        INSERT OR REPLACE INTO antutu_benchmarks (
            phone_id, total_score, cpu_score, gpu_score, mem_score, ux_score, version, tested_date, source, verified
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 1)
        """, (
            item["id"],
            b["total_score"],
            b["cpu_score"],
            b["gpu_score"],
            b["mem_score"],
            b["ux_score"],
            b["version"],
            b["tested_date"],
            b["source"]
        ))

        # 4. Market prices
        m = item["market"]
        cursor.execute("""
        INSERT OR REPLACE INTO market_prices (
            phone_id, price_new_uzs, price_new_formatted, new_shops_json,
            price_used_avg_uzs, price_used_excellent_uzs, price_used_good_uzs, price_used_fair_uzs,
            market_notes, last_updated, sources_links_json
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            item["id"],
            m["price_new_uzs"],
            m["price_new_formatted"],
            m["new_shops_json"],
            m["price_used_avg_uzs"],
            m["price_used_excellent_uzs"],
            m["price_used_good_uzs"],
            m["price_used_fair_uzs"],
            m.get("market_notes", ""),
            m["last_updated"],
            m.get("sources_links_json", "[]")
        ))

    conn.commit()
    conn.close()
    print("Barcha ma'lumotlar muvaffaqiyatli saqlandi!")

